const ability = (
  characterId: string,
  id: string,
  name: string,
  actionType: string,
  description: string,
  costs: AbilitySummary["costs"],
  recommendedNex: number,
  position: number,
): AbilitySummary => ({
  id,
  characterId,
  name,
  actionType,
  description,
  state:
    characterId === "gragas"
      ? "sealed"
      : characterId === "davi" && position === 1
        ? "masked"
        : position <= 2
          ? "unlocked"
          : "sealed",
  costs,
  limit: position === 6 ? "1/missão" : undefined,
  recommendedNex,
});

